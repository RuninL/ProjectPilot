export function cloneSnapshot(snapshot = createCompleteSnapshot()): DatabaseSnapshot {
  return structuredClone(snapshot);
}

export function createTransferHarness(db = createTestDb()) {
  const repository = createDataTransferRepository(db.executor);
  const runBatch = vi.fn((statements: Parameters<TestDb['runBatch']>[0]) =>
    Promise.resolve(db.runBatch(statements)),
  );
  const service = createDataTransferService({ repository, runBatch });
  return { db, repository, runBatch, service };
}

export function seedSnapshot(db: TestDb, snapshot = createCompleteSnapshot()): void {
  const repository = createDataTransferRepository(db.executor);
  db.runBatch(repository.buildInsertStatements(snapshot));
}

export async function createCompleteExport(
  db: TestDb,
  includeSample = true,
): Promise<ProjectPilotExport> {
  const repository = createDataTransferRepository(db.executor);
  const service = createDataTransferService({
    repository,
    runBatch: (statements) => Promise.resolve(db.runBatch(statements)),
  });
  return service.exportData('0.1.0', NOW, includeSample);
}
